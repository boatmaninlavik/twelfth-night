/**
 * 「别人这么写」—— 故事页输入框下面的示例。
 *
 * 故事页原来只有一句提示语「不用写得漂亮，真诚就好」。那句话解的是
 * 「写得丑怎么办」，可人真正卡住的是「不知道写什么」—— 两件事。
 *
 * 而 server/src/lyrics.js 那条 prompt 里明写着：
 *   「**必须用故事里的具体细节** —— 具体的物、具体的时间、具体的动作。
 *     写"我爱你""好想你""你是我的光"这类句子等于没写。」
 * 用户写「她很温柔，我很爱她」，模型只能还回被自己禁掉的那种词。
 * 所以这些示例的任务不是"好看"，是**示范颗粒度**。
 *
 * 写这些句子守三条：
 *
 *   1. 示范的是**颗粒度，不是文采**。写得漂亮反而更卡人 —— 人一看就觉得
 *      「我写不到那么好」，然后什么都不写。所以**故意写得有点笨**：
 *      短句、白话、不用比喻、不抒情、不总结。
 *
 *   2. 每一条都得有**物、时间、动作**里的至少两样。
 *      「我妈对我很好」是坏示例；「她塞了两罐咸菜进我包，外面缠了好几圈胶带」
 *      是好示例 —— 后者能直接长进歌词，前者只能还回一句空话。
 *
 *   3. **一个人名都不出现。** 歌词里不许出现人名（lyrics.js 里禁了，
 *      还有 stripToName() 兜底），示例当然也不能示范人名 ——
 *      示例写什么，用户就跟着写什么。一律用「她/他/我妈/奶奶」这类称谓。
 *
 * 按场合分组，键跟 pages/order 的 occasions 对齐。
 * 场合没选（「不指定」）时走 FREE —— 那一组特意都是**没有收信人**的，
 * 因为很多歌本来就不是写给谁的，是想唱出来。
 */
