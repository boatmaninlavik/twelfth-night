/* 「不指定」那一组。
   刻意全都**没有收信人** —— 很多歌不是写给谁的，是想唱出来。
   定歌页「给谁」那一栏也可以留空，这一组示范的就是那种写法。 */
const FREE = [
  '今年搬了三次家。最后这间窗外有棵树，早上六点有鸟在上面吵。本来想投诉，后来每天醒着听。',
  '我每天下班走同一条路，有家面包店七点半打折。有段时间我会故意走慢一点，刚好赶上。',
  '手机里有张照片是去年拍的，当时觉得没什么，现在每隔一阵会翻出来看一次。',
];

/** 取这个场合的示例。没选场合、或者场合不在表里，都退回 FREE。 */
function forOccasion(occasion) {
  return DECKS[occasion] || FREE;
}

module.exports = { forOccasion };
