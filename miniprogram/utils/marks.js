/**
 * 「记下了」—— 把用户自己写的具体东西挑出来，原样还给他。
 *
 * 这是整条引导里最有效的一处。用户写完「去年冬天我烧到三十九度，凌晨给她打电话，
 * 第二天早上她拎着保温桶站在我门口」，下面浮出一行：
 *
 *     记下了　冬天 · 三十九度 · 凌晨 · 保温桶
 *
 * 他立刻就懂了这一页要的是什么颗粒度 —— 比任何提示语都管用，
 * 因为示范用的是**他自己的话**，不是我们编的范文。
 *
 * 实现上刻意做成**宁可漏、不可错**：
 *   · 只认高置信度的写法（数量词、时间词、地点词、一份人工挑的实物表）
 *   · 认不出两个以上就整块不显示 —— 没有反馈，好过一行胡说八道的反馈
 * 中文分词放在端上做不到又准又小，而这一处错一次的代价比不出现高得多：
 * 用户看见「记下了：的时候 · 一个」会立刻不信任这整页。
 *
 * 不上服务端是故意的：这是打字停顿时的即时反馈，走一趟网络就废了。
 * 真要做准，该做的不是在这儿堆规则，是把这一步并进 lyrics.js 那次调用里
 * 让模型顺手返回 —— 但那要等到出词之后，太晚，反馈的意义正在于"当场"。
 */

/** 数量：数字 + 量词。「三十九度」「六十二岁」「两碗」「三站」都在这儿。 */
const QUANT = /[0-9０-９零一二三四五六七八九十百千万两半]+\s*(?:度|岁|年|个月|个星期|个礼拜|月|周|天|夜|号|日|点|分钟|小时|秒|块钱|块|元|毛|次|遍|趟|站|层|楼|排|米|公里|里地|斤|克|吨|瓶|杯|碗|盘|碟|包|袋|盒|罐|张|条|件|双|只|把|支|颗|粒|根|台|辆|间|套|页|封|通|口|岁半|人)/g;

/** 时间。相对时间比绝对日期更常出现在口语里，所以这张表以相对为主。 */
const TIME = /(?:前年|去年|今年|明年|那年|上个月|这个月|下个月|上周|上礼拜|这周|昨天|前天|当天|第二天|头一天|那天|那晚|那年|今早|一早|凌晨|清晨|早上|上午|中午|下午|傍晚|晚上|半夜|深夜|周末|平时|每天|每年)/g;

/** 季节与节令。带年份感的词，写进歌词特别管用。 */
const SEASON = /(?:开春|春天|入夏|夏天|入秋|秋天|入冬|冬天|春节|过年|除夕|初一|中秋|元旦|清明|端午|生日|忌日|高考|中考|毕业|开学)/g;

/** 地点。只收具体到"能站进去"的那种，不收「城市」「地方」这类抽象词。 */
const PLACE = /(?:医院|急诊|病房|诊所|药店|学校|教室|操场|校门口|宿舍|食堂|图书馆|车站|火车站|高铁站|汽车站|机场|地铁|公交|出租屋|老家|客厅|厨房|阳台|卧室|书房|楼下|楼道|门口|院子|办公室|工位|会议室|便利店|菜市场|超市|理发店|电影院|公园|操场|球场|天台|巷子|路口)/g;

/**
 * 实物。这一张是人工挑的，标准只有一条：**能被唱进歌里**。
 * 「东西」「物品」「事情」这种词一个都不要 —— 它们是抽象词穿了名词的皮。
 */
const THING = /(?:保温桶|饭盒|便当|水杯|杯子|保温杯|碗筷|锅|汤|粥|面条|饺子|馒头|米饭|鸡蛋|苹果|橘子|橙子|西瓜|糖|硬糖|奶糖|巧克力|药|药片|校服|球衣|卫衣|毛衣|外套|大衣|羽绒服|围巾|手套|帽子|鞋|球鞋|拖鞋|袜子|裙子|衬衫|雨伞|伞|书包|背包|钱包|钥匙|钥匙扣|手表|眼镜|戒指|项链|耳机|手机|台灯|闹钟|风扇|电视|自行车|摩托车|三轮车|公交卡|车票|机票|门票|照片|相册|信|明信片|日记本|课本|作业本|笔记本|铅笔|钢笔|红笔|粉笔|黑板|绿萝|多肉|盆栽|花|玫瑰|向日葵|猫|狗|烟|酒|茶|咖啡|奶茶)/g;

/**
 * 职业与身份。
 *
 * 「退休前是护士」里的「护士」是这一整句最具体的一个词 —— 不收它，
 * 「ta 是谁」那一问答得再好也一个标记都挑不出来，用户会觉得这功能坏了。
 * 这些词歧义极低，收进来几乎不会误伤。
 */
const ROLE = /(?:护士|医生|大夫|老师|班主任|教授|同学|同事|室友|发小|司机|会计|出纳|程序员|工程师|设计师|建筑师|警察|消防员|军人|厨师|服务员|店员|快递|外卖|保安|门卫|工人|农民|律师|记者|编辑|销售|客服|理发师|修理工|保姆|月嫂|裁缝|木匠|司机|学徒|实习生|退休)/g;

const SOURCES = [QUANT, TIME, SEASON, PLACE, ROLE, THING];

/** 少于这个数就整块不显示。一个孤零零的「那天」不足以说明问题。 */
const MIN = 2;

/** 最多挑几个。挑太多这一行就从"点睛"变成"清单"了。 */
const MAX = 6;

/**
 * 收集所有命中的区间。
 *
 * 必须按**区间**收而不是按字符串收，因为要处理重叠：
 * 「凌晨三点」会被 TIME 命中「凌晨」、被 QUANT 命中「三点」，
 * 两段首尾相接 —— 拼回一个词比拆成两个好看得多。
 */
function spans(text) {
  const out = [];
  for (const re of SOURCES) {
    re.lastIndex = 0;                       // 全局正则带状态，复用前必须归零
    let m;
    while ((m = re.exec(text)) !== null) {
      if (!m[0]) { re.lastIndex++; continue; }   // 零宽匹配会死循环
      out.push({ start: m.index, end: m.index + m[0].length });
    }
  }
  return out.sort((a, b) => a.start - b.start || b.end - a.end);
}

/** 合并重叠与首尾相接的区间：「凌晨」+「三点」→「凌晨三点」。 */
function merge(list) {
  const out = [];
  for (const s of list) {
    const last = out[out.length - 1];
    if (last && s.start <= last.end) {     // <= 而不是 <：相接也合
      last.end = Math.max(last.end, s.end);
    } else {
      out.push({ ...s });
    }
  }
  return out;
}

/**
 * 从一段文字里挑出具体的东西。
 * 返回 [] 表示"没挑出足够的"，调用方据此整块不显示。
 */
function pick(text) {
  const s = String(text || '');
  if (s.length < 6) return [];

  const words = merge(spans(s)).map((r) => s.slice(r.start, r.end).trim()).filter(Boolean);

  // 去重，保留先后次序 —— 次序就是他讲述的次序，读起来才像他的话。
  const seen = new Set();
  const uniq = [];
  for (const w of words) {
    if (seen.has(w)) continue;
    seen.add(w);
    uniq.push(w);
  }

  return uniq.length >= MIN ? uniq.slice(0, MAX) : [];
}

/** 只要个数（合稿页那行"记下了 N 个只有你知道的细节"用）。 */
function count(text) {
  const s = String(text || '');
  if (s.length < 6) return 0;
  const words = merge(spans(s)).map((r) => s.slice(r.start, r.end));
  return new Set(words).size;
}

module.exports = { pick, count, MIN };
