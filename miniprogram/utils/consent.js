/**
 * 声音授权。两层，不能合并成一层。
 *
 *   第一层  按下录音键之前  单独同意弹窗   解决敏感个人信息的「单独同意」
 *   第二层  提交订单的那一下  电子签授权书   解决声音权益的使用授权与责任划分
 *
 * 法律基础：
 *   ·《民法典》1023 条 —— 自然人的声音参照肖像权保护
 *   ·《个人信息保护法》28–30 条 —— 生物识别信息属敏感个人信息，须**单独同意**、单独告知
 *   ·《个人信息保护法》15、47 条 —— 可随时撤回；撤回或目的实现后应主动删除
 *
 * 最常见的错法是把这两层塞进用户协议里勾一个框。那在法律上很可能不构成有效的
 * 单独同意 —— 等于整条授权链从第一步就断了。所以：
 *   · 两个弹窗各自独立，不与任何其他协议合并
 *   · 勾选框**默认不勾**，而且不写「我已阅读并同意全部协议」这类打包表述
 *   · 拒绝第一层**不挡下单** —— 换歌手音色照样能把歌做完
 *
 * ⚠️ 文案与代码必须对得上。这里每一句承诺都对应 server 里真实存在的行为：
 * 原稿里「声线模型保存 12 个月」这类说法本文件**没有照抄**，因为这套后端
 * 根本不存可复用的声线模型（pipeline.js 的换声是一次性的）。
 * 承诺一件产品做不到的事，比不承诺糟糕得多。
 * 以后真做了「回来做第二首」，必须回来改这段文字**并让老用户重新同意**。
 *
 * 【】括起来的是上线前必须替换的占位符，别带着它们发版。
 */

