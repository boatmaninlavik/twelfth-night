/* ── 存证 ─────────────────────────────────────────────
   授权书本身不重要，**能证明"这个人在这个时间确实同意了"才重要**。
   下面这些字段就是出事时会被拿出来看的东西。

   「滚动到底」这一项最容易被忽略，但它是证明用户有机会读完全文的直接证据，
   技术上不过是接一个 bindscrolltolower，成本几乎为零。 */

/**
 * 装配一份存证。
 * @param {object} o
 *   layer     1 | 2
 *   version   条款版本号
 *   checks    勾选动作的结果，长度与 checks 一致
 *   shownAt   弹窗打开的时间戳（用来算展示时长 —— 秒开秒关的同意是站不住的）
 *   readEnd   是否滚动到过底部
 *   extra     额外字段（第二层带录音哈希和提示语）
 */
function evidence(o) {
  const now = Date.now();
  let dev = {};
  try {
    // getDeviceInfo / getAppBaseInfo 是新接口，老基础库上没有，退回 getSystemInfoSync。
    const d = wx.getDeviceInfo ? wx.getDeviceInfo() : wx.getSystemInfoSync();
    const a = wx.getAppBaseInfo ? wx.getAppBaseInfo() : wx.getSystemInfoSync();
    dev = {
      brand: d.brand, model: d.model, system: d.system,
      platform: d.platform || a.platform,
      sdk: a.SDKVersion, appVersion: a.version,
    };
  } catch (e) { /* 取不到设备信息不该挡住签署 */ }

  return {
    layer: o.layer,
    version: o.version,
    signedAt: new Date(now).toISOString(),
    dwellMs: o.shownAt ? now - o.shownAt : null,   // 展示时长
    readToEnd: !!o.readEnd,                        // 滚动到底
    checks: (o.checks || []).slice(),              // 勾选动作
    device: dev,
    ...(o.extra || {}),
  };
}


/* ── 第一层的本地状态 ─────────────────────────────────
   注意：这只是"这台设备上这个人同意过"的缓存，**不是**存证本身。
   真正的存证随订单送到服务端（record.js 下单时带上），
   本地这份只用来决定下次进录音页要不要再问一遍。 */

function readL1() {
  try { return wx.getStorageSync(L1_KEY) || null; }
  catch (e) { return null; }                       // 隐私模式下 storage 会抛
}

/** 没同意过、或者条款已经改版，都要重新问。 */
function needsL1() {
  const r = readL1();
  return !r || r.version !== L1_VERSION;
}

function saveL1(ev) {
  try { wx.setStorageSync(L1_KEY, ev); } catch (e) { /* 存不下就这一次有效 */ }
}

/** 撤回。本地先清干净，服务端那一半由调用方去删（api.deleteVoice）。 */
function clearL1() {
  try { wx.removeStorageSync(L1_KEY); } catch (e) { /* 清不掉也别崩 */ }
}

/** 签过的授权书留一份在本机，「我的」里要能查回来。只留最近 20 份。 */
function saveL2(ev) {
  try {
    const all = wx.getStorageSync(L2_KEY) || [];
    all.unshift(ev);
    wx.setStorageSync(L2_KEY, all.slice(0, 20));
  } catch (e) { /* 存不下不该挡住下单 */ }
}

function listL2() {
  try { return wx.getStorageSync(L2_KEY) || []; }
  catch (e) { return []; }
}

module.exports = {
  L1, L2, L1_VERSION, L2_VERSION, AGE_BANDS, l1,
  evidence, readL1, needsL1, saveL1, clearL1, saveL2, listL2,
};
