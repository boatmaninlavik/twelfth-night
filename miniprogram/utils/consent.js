/**
 * 按年龄档拼出第一层的完整条款。
 * 没选年龄时返回的 checks 是空的 —— 界面据此不显示勾选框，
 * 逼着人先回答年龄这一问，而不是让他勾完了才发现问错了对象。
 */
function l1(ageBand) {
  if (ageBand === 'teen' || ageBand === 'child') {
    return {
      ...L1,
      sections: ageBand === 'child'
        ? [...L1.sections, GUARDIAN, CHILD_RULES]
        : [...L1.sections, GUARDIAN],
      checks: [
        '我是 ta 的监护人',
        ageBand === 'child'
          ? '我已阅读上述内容和专门规则，同意由我代 ta 作出本次授权'
          : '我已阅读上述内容，同意由我代 ta 作出本次授权',
      ],
      agree: '代为同意，开始录音',
    };
  }
  if (ageBand === 'adult') return { ...L1, checks: [SELF_CHECK], agree: '同意，开始录音' };
  return { ...L1, checks: [], agree: '同意，开始录音' };
}


