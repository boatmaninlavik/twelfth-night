/**
 * 提词。
 *
 * 故事页原来是一个 800 字的空框，提示语写着「不用写得漂亮，真诚就好」。
 * 那句话解的是「写得丑怎么办」，可人卡住的是「不知道写什么」—— 两件事。
 *
 * 而 server/src/lyrics.js 那条 prompt 里明写着：
 *   「**必须用故事里的具体细节** —— 具体的物、具体的时间、具体的动作。
 *     写"我爱你""好想你""你是我的光"这类句子等于没写。」
 * 用户写"她很温柔，我很爱她"，模型只能还回被自己禁掉的那种词。
 * 所以这一页的活儿不是"收一段文字"，是**逼出三五个只有他知道的细节**。
 *
 * 办法是把「写一段」换成「答三句」：发四张提词卡，挑一张答，
 * 再补「ta 是谁」和「一个细节」。问答体在这套视觉里不是妥协 ——
 * 剧本本来就是一行人名一行台词往下走的，这是回到本体。
 *
 * 这个文件是这一版真正的工作量。句子写得好不好决定这个设计成不成立，
 * 代码反而是简单的那一半。改动时守住四条：
 *
 *   1. 每一句都得**答得上来**。问"你们的爱情是什么"没人答得上，
 *      问"最近一次见面 ta 在做什么"谁都答得上。
 *
 *   2. 问的是**事**，不是**感受**。感受用户会自己写成"很温暖"，
 *      事才带得出物、时间和动作。
 *
 *   3. **凡是能用一个名词或一个判断答完的问题，都是坏问题。**
 *      这一条是后加的，它把前两条量化了，可以拿来逐条验牌：
 *        · "我们是怎么认识的" → 答"大学同学"。传记题，产出的是交代性文字，
 *          交代在歌词里最难用，一唱就垮。
 *        · "哪个地方最难忘" → 答一个地名就结束了。评价题，"最"字一出现，
 *          用户给的是排名不是画面。
 *        · "我第一次注意到 ta 是什么时候" → 答"去年秋天"。时间点不是场景。
 *      改法一律是**把问题的落点从"哪一个"挪到"当时什么样"**：
 *      "第一次见到 ta，那天 ta 在做什么"。名词答不完，人只能开始描述。
 *
 *   4. eg 那行小字示范的是**颗粒度**，不是文采。写得漂亮反而更卡人 ——
 *      人一看就觉得"我写不到那么好"。故意写得有点笨。
 *
 * 另外补了一类以前整副牌都没有的题：**一样东西**。
 * 副歌需要一个能反复出现的意象（《晴天》的操场、《七里香》的窗台），
 * 而原来八副牌一张都没问过物件 —— 问到的全是事和话。
 * 每副牌现在至少留一张给它。
 */

