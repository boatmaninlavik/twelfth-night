/** 一次发几张牌。四张：三张挑不出来，五张开始像考卷。 */
const HAND = 4;

/** 洗牌。Fisher–Yates，别用 sort(() => Math.random() - .5) —— 那个不是均匀的。 */
function shuffle(a) {
  const out = a.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/**
 * 按场合取一副洗好的牌。
 * 返回的是整副，页面自己按 HAND 切 —— 「换一批」就是往后挪一手，
 * 挪到底再从头来，所以八到十张够翻两轮。
 */
function deck(occasion) {
  return shuffle(DECKS[occasion] || DEFAULT_DECK);
}

/** 把题面里的 {name} 和 {br} 填掉。{br} 是手动断行位，配合 .h1 的 pre-line。 */
function fill(tpl, name) {
  return String(tpl)
    .replace(/\{name\}/g, name || 'ta')
    .replace(/\{br\}/g, '\n');
}

